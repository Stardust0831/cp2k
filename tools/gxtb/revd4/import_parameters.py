"""Generate CP2K's numerical D4Srev tables from axtb commit 65d0f64."""
import argparse
import ast
import hashlib
import math
import re
from pathlib import Path


def source(root, name, digest):
    raw = (root / name).read_bytes()
    if hashlib.sha256(raw).hexdigest() != digest:
        raise ValueError(f"Unexpected source checksum for {name}")
    return raw.decode()


def table(text, name):
    match = re.search(rf"^(?:pub static|const) {name}: [^=]+?= (\[.*?\n\]);", text, re.M | re.S)
    return ast.literal_eval(re.sub(r"//[^\n]*", "", match[1]))


def generate(root):
    old = source(root, "crates/gxtb/src/data/v1_1.rs",
                 "e835ef0969c8d6c96bd5f6b75bd31b8952edab4c670bdf14f74cb8d9d878fc19")
    new = source(root, "crates/gxtb/src/data/v2_0_1.rs",
                 "455370c18613e0f654f8f1a7005acd4138d9d843ed00d621d704f32c29da3df7")
    d4 = source(root, "crates/d4/src/data.rs",
                "1e10ae71ee7e3b27ce2b031ce9f8b43c2891ddf800a0c68dccca9b9da62fc870")
    grid = source(root, "crates/d4/src/model.rs",
                  "029f0dc23006ea020d8157de3e58317a0e0ce8e1d45771c1cfa9967be4ad2e14")
    cn, covcn, tanh, width = [table(old, key) for key in ("D4_REFCN", "D4_REFCOVCN", "D4_TANH", "K3_PAIR")]
    refq, refh, rcov = [table(new, key) for key in ("D4_REFQ", "D4_REFH", "D4_RCOV")]
    count, ratio, sec, ascale, hcount, sscale, sai, ai = [
        table(d4, key) for key in ("REFN", "R4_OVER_R2", "REFSYS", "ASCALE", "HCOUNT", "SSCALE", "SECAIW", "ALPHAIW")]
    freq = table(grid, "FREQ")
    quad = [math.sqrt(3 / (2 * math.pi) * (freq[min(k+1, 22)] - freq[max(k-1, 0)])) for k in range(23)]

    def charge(i, q):
        a, b, c, d = tanh[4*i:4*i+4]
        return a + b * math.tanh(c*q + d)

    def values(seq):
        return ", ".join(map(repr, seq))

    elements, references, widths = [], [], []
    for i in range(103):
        n = count[i]
        first = len(references)
        r4r2 = math.sqrt(0.5 * ratio[i] * math.sqrt(i+1))
        elements.append("  {" + values([first, n, rcov[i], r4r2]) + ", {" + values(tanh[4*i:4*i+4]) + "}},")
        shells = [min(19, max(0, math.floor(x+0.5))) for x in cn[7*i:7*i+n]]
        for j, shell in enumerate(shells):
            multiplicity = shells.count(shell) + int(shell == 0)
            site = sec[i][j] - 1
            response = [0.0] * 23
            if site >= 0:
                hydrogen = hcount[i][j] * sscale[site] * charge(site, refh[7*i+j]) / charge(site, 0)
                # Fold the fixed trapezoid weights and reference charge normalization
                # into the tabulated frequency response. C6 is then a dot product.
                for k, weight in enumerate(quad):
                    alpha = max(0, ascale[i][j] * (ai[i][j][k] - hydrogen * sai[site][k]))
                    response[k] = weight * alpha / charge(i, refq[7*i+j])
            references.append("  {" + values([covcn[7*i+j], multiplicity*(multiplicity+1)//2]) +
                              ", {" + values(response) + "}},")
        for j in range(i+1):
            assert width[i*103+j] == width[j*103+i]
        widths.append("  " + values(width[i*103:i*103+i+1]) + ",")
    return "\n".join([
        "// SPDX-License-Identifier: LGPL-3.0-or-later",
        "// Numerical model data from g-xTB, dftd4 and axtb. See tools/gxtb/revd4/PARAMETERS.md.",
        "// Generated by import_parameters.py. Element and reference indices are zero-based.",
        "constexpr Element elements[] = {", *elements, "};",
        "constexpr Reference references[] = {", *references, "};",
        "constexpr double pair_widths[] = {", *widths, "};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("axtb", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.axtb))
