"""Generate numerical g-xTB 2.0.1 electronic parameters used by CP2K."""
import argparse
from pathlib import Path

from import_parameters import source, table


def generate(root):
    new = source(root, "crates/gxtb/src/data/v2_0_1.rs",
                 "455370c18613e0f654f8f1a7005acd4138d9d843ed00d621d704f32c29da3df7")
    old = source(root, "crates/gxtb/src/data/v1_1.rs",
                 "e835ef0969c8d6c96bd5f6b75bd31b8952edab4c670bdf14f74cb8d9d878fc19")
    fields = ("INCREMENT", "CN_RCOV", "REP_ALPHA", "REP_CN", "REP_ZEFF", "REP_Q",
              "REP_ROFFSET", "REP_K1", "RVDW_SCALE", "FOCK_CSCALE", "FOCK_CRAD")
    rows = list(zip(*(table(new, name) for name in fields), strict=True))
    radii = table(old, "VDW_RAD_PACKED")
    if len(rows) != 103 or len(radii) != 103 * 104 // 2:
        raise ValueError("Unexpected element count in g-xTB tables")
    # The fitted scale includes one bohr in angstrom, which cancels the
    # angstrom-to-bohr conversion of the tabulated D3 radius.
    hubbard, shell, power, onsite = (table(new, key) for key in
                                    ("HUBBARD", "FOCK_SHELL_HUBBARD", "FOCK_AVG_EXP", "ONECX"))
    ipea_cn, dh, ipea, n0, zeff, wll, spin = (table(new, key) for key in
        ("IPEA_CN", "HUBBARD_DERIV", "IPEA", "REF_OCC", "ZEFF_SHELL", "WLL_SCALE", "SPIN_W0"))
    elements = []
    for i, row in enumerate(rows):
        values = [*row[:8], row[8] / 0.5291772109044924, *row[9:]]
        arrays = ([v * hubbard[i] for v in shell[i]], power[i], onsite[i])
        electrostatic = (ipea[i], [x-y for x,y in zip(n0[i], zeff[i])], [v*wll[i] for v in spin[i]])
        def array_text(a):
            return "{" + ", ".join(map(repr, a)) + "}"
        elements.append("  {" + ", ".join([*map(repr, values), *map(array_text, arrays),
                        repr(ipea_cn[i]), repr(dh[i]), *map(array_text, electrostatic)]) + "},")
    return "\n".join(["// SPDX-License-Identifier: LGPL-3.0-or-later",
                      "// Numerical data and attribution in tools/gxtb/revd4/PARAMETERS.md.",
                      "// Generated by import_electronic.py.", "constexpr Element elements[] = {",
                      *elements, "};", "constexpr double d3_pair_radius[] = {",
                      *["  " + ", ".join(map(repr, radii[i:i+12])) + "," for i in range(0, len(radii), 12)],
                      "};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("axtb", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.axtb))
