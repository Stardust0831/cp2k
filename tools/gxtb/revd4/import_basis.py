"""Import the g-xTB basis and one-electron numerical parameters."""
import argparse
from pathlib import Path

from import_parameters import source, table


def literal(items):
    return "{" + ", ".join(literal(x) if isinstance(x, list) else repr(x) for x in items) + "}"


def generate(root):
    model = source(root, "crates/gxtb/src/data/v2_0_1.rs",
                   "455370c18613e0f654f8f1a7005acd4138d9d843ed00d621d704f32c29da3df7")
    common = source(root, "crates/gxtb/src/data/v1_1.rs",
                    "e835ef0969c8d6c96bd5f6b75bd31b8952edab4c670bdf14f74cb8d9d878fc19")
    basis = source(root, "crates/gxtb/param/basisq",
                   "f88fade9010423a62dd498640cb663a6e19655d91a6220b72dccce7a512a0103")
    lines = iter(x.split() for x in basis.splitlines() if x.strip() not in ("", "*"))
    fields = ("NSHELL", "ACP_N", "H0_K0_SCALE", "H0_K2_SCALE", "H0_K3_SCALE",
              "H0_SHPOLY2", "H0_DIP_SCALE", "H0_SELFENERGY", "H0_SELFENERGY_CN",
              "H0_EXP_SCALE", "H0_DIAT_SCALE", "REF_OCC", "ACP_L", "ACP_LEVEL", "ACP_EXP",
              "SHELL_HUBBARD", "HUBBARD", "HUBBARD_CN", "AES_DIP_SCALE")
    cov = table(common, "RCOV_BASIS_CN")
    radius = table(common, "RCOV_COM")
    en = table(common, "PAULING_EN")
    eq = list(zip(*(table(model, "EEQBC_" + key) for key in
                  ("CHI", "ETA", "RAD", "KCNCHI", "KQCHI", "CAP", "COV_RADII", "AVG_CN", "RVDW_SCALE")), strict=True))
    atoms, shells = [], []
    for z, row in enumerate(zip(*(table(model, key) for key in fields), strict=True), 1):
        count, nproj, *coeff = row
        number, *charge = next(lines)
        if int(number) != z:
            raise ValueError(f"Expected basis for element {z}, found {number}")
        fitted_radius = {1: 0.403, 9: 0.50, 10: 0.61}
        r = 1.889725949 * fitted_radius[z] if z in fitted_radius else radius[z-1]
        atoms.append([len(shells), count, nproj, list(map(float, charge)), coeff[:3],
                      cov[z-1], r, *coeff[3:-4], [v*coeff[-3] for v in coeff[-4]],
                      *coeff[-2:], [*eq[z-1], en[z-1]/3.98]])
        for _ in range(count):
            n, symbol = next(lines)
            prim = [list(map(float, next(lines))) for _ in range(int(n))]
            shells.append(["spdf".index(symbol), int(n), *map(list, zip(*prim, strict=True))])
    if len(atoms) != 103 or next(lines, None) is not None:
        raise ValueError("Unexpected basis table length")
    return "\n".join(["// SPDX-License-Identifier: LGPL-3.0-or-later",
                      "// Numerical data and attribution in tools/gxtb/revd4/PARAMETERS.md.",
                      "// Generated by import_basis.py.", "constexpr BasisData basis_table[] = {",
                      *("  " + literal(row) + "," for row in atoms), "};",
                      "constexpr ShellData shell_table[] = {",
                      *("  " + literal(row) + "," for row in shells), "};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("axtb", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.axtb))
